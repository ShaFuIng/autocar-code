const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(__dirname+'/pid.js','utf8');
const start=source.indexOf('function cameraCollinearity(');
const end=source.indexOf('/* Camera measurement UI:',start);
const context={};vm.createContext(context);vm.runInContext(source.slice(start,end),context);
const check=pts=>context.cameraCollinearity(pts.map((left,i)=>({cm:[50,80,120][i],left})),'left');
assert.equal(check([[0,0],[5,5],[10,10]]).deviation,0);
assert.equal(check([[0,0],[4,5],[0,10]]).deviation,4);
assert.equal(check([[0,0],[5,3],[10,0]]).deviation,3);
assert.ok(Math.abs(check([[0,0],[0,2],[2,2]]).deviation-Math.SQRT2)<1e-10);
assert.equal(check([[0,0],[1,1],[0,0]]),null);
assert.equal(check([[0,0],[NaN,1],[2,2]]),null);
assert.equal(context.cameraCollinearity([],'left'),null);
const pts=[[105.244458,252.222249],[159.022168,196.222249],[223.022249,161.688896]];
const before=JSON.stringify(pts),d=check(pts).deviation;
assert.ok(d>11&&d<12);
assert.equal(JSON.stringify(pts),before);
assert.ok(Math.abs(check(pts.map(p=>p.map(v=>v*2))).deviation-2*d)<1e-9);
console.log('10 camera collinearity assertions passed; saved left deviation:',d.toFixed(1),'px');
