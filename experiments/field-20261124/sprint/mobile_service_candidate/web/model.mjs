export const reasonText = (code,text) => reasons[code] || (text?`車端回覆：${text}`:'車端尚未允許此操作，請查看狀態與診斷資訊。');
export function duration(v){if(!Number.isFinite(v)||v<0)return '—';const d=Math.floor(v*10);return `${Math.floor(d/600)}:${String(Math.floor(d/10)%60).padStart(2,'0')}.${d%10}`;}
export function stateOf(s){if(!s?.run)return 'ready';if(s.run.state==='ended')return 'ended';return s.pause?.state==='paused'?'paused':s.run.state;}
export function pathPoints(frame){const {mask,path}=frame;if(!mask||!path||!(path.width>0&&path.height>0))return [];return (path.points||[]).filter(p=>Array.isArray(p)&&p.length===2&&p.every(Number.isFinite)).map(([x,y])=>[x*mask.width/path.width,y*mask.height/path.height]);}
export function expected(command,s){const state=stateOf(s);if(command.action==='prepare')return s.model_ready===true;if(command.action==='start')return !!s.run&&s.run.id!==command.previousRun&&['running','paused'].includes(state);if(command.action==='stop')return !s.run||state==='ended';if(s.run?.id!==command.run_id)return false;return command.action==='pause'?state==='paused':state==='running';}
export function permissions(s,connected,waiting){const state=stateOf(s),active=['running','paused'].includes(state);return {active,prepare:connected&&!waiting&&!active,start:connected&&!waiting&&!active&&s?.model_ready===true&&!s?.fault,pause:connected&&!waiting&&state==='running'&&s?.pause?.can_pause!==false,resume:connected&&!waiting&&state==='paused'&&s?.pause?.can_resume===true,stop:true};}
